//! Agreement between the committed wire-contract JSON Schema artifact and the
//! strict custom-resource request decoder.
//!
//! `RawDeploymentRequest` (and every nested `Raw*` struct) declares its wire
//! keys with `#[serde(rename_all = "PascalCase")]`, `deny_unknown_fields`, and
//! serde defaults that decide requiredness. The TypeScript side declares the
//! same contract once in `contract/wire-contract.mjs` as the runtime
//! `ResourceProperties` schema (`wireContractSchema`) and renders it to
//! `contract/wire-schema.json`. Nothing derives one side from the other, so
//! this test binds them: it loads the committed artifact and asserts the
//! decoder agrees with it in both directions. A rename, an added key, a
//! dropped key, or a requiredness change on either side alone fails here.
//!
//! Value acceptance is bound the same way by the acceptance matrix in
//! `contract/wire-acceptance-matrix.json`, which both sides run: every case
//! sets one value at one wire path, and the schema and the decoder must agree
//! on whether the payload is accepted. The matrix covers every union branch,
//! nullability, whitespace, casing, and the integer overflow boundary.
//!
//! The artifact is regenerated by `scripts/generate-wire-schema.mjs` and the
//! `verify:wire-contract` gate fails when it drifts from the schema, so this
//! test always exercises the exact artifact that will be committed.

#[cfg(test)]
